// Package gen generates Go source from a parsed WSDL type model.
//
// Generation rules that exist because real generators get them wrong:
//
//   - Any particle whose occurrence bounds allow more than one value
//     (maxOccurs > 1 or unbounded, on the element itself OR on an
//     enclosing choice/sequence) becomes a slice. Never a single field:
//     a single field silently drops occurrences at unmarshal time.
//   - xs:choice generates one field per member element. encoding/xml
//     cannot enforce mutual exclusion; the limit is documented in the
//     generated doc comments, never hidden.
//   - Type names that collide across namespaces are deterministically
//     qualified, so no type silently redefines another.
package gen

import (
	"fmt"
	"go/format"
	"sort"
	"strings"
	"unicode"

	"github.com/ofershap/lather/wsdl"
)

// Options control generation.
type Options struct {
	Package string // Go package name for generated code
}

// Generate renders the Go source for d.
func Generate(d *wsdl.Definitions, opts Options) ([]byte, error) {
	if opts.Package == "" {
		opts.Package = "myservice"
	}
	g := &generator{d: d, names: map[string]int{}, emitted: map[string]string{}, root: map[string]rootInfo{}, wrap: map[string]wrapInfo{}}
	g.collectNameCollisions()
	g.markRoots()

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by lather (https://github.com/ofershap/lather) from WSDL %q. DO NOT EDIT.\n\n", d.Name)
	fmt.Fprintf(&b, "package %s\n\n", sanitizeIdent(opts.Package))
	var clientBuf strings.Builder
	g.client(&clientBuf)

	b.WriteString("import (\n\t\"encoding/xml\"\n\t\"strings\"\n\t\"time\"\n")
	if clientBuf.Len() > 0 {
		b.WriteString("\t\"context\"\n\n\t\"github.com/ofershap/lather/soap\"\n")
	}
	b.WriteString(")\n\n")
	b.WriteString(helperTypes)

	for _, sc := range d.Schemas {
		names := sortedKeys2(sc.Types, sc.Simple)
		for _, name := range names {
			if ct, ok := sc.Types[name]; ok {
				g.complex(&b, sc, ct)
			} else {
				g.simple(&b, sc, sc.Simple[name])
			}
		}
		for _, name := range sortedKeys(sc.Elements) {
			g.globalElement(&b, sc, sc.Elements[name])
		}
	}
	b.WriteString(clientBuf.String())
	out := []byte(b.String())
	if formatted, ferr := format.Source(out); ferr == nil {
		out = formatted
	}
	return out, nil
}

// client emits a typed service client over the lather soap runtime:
// one method per portType operation, with the SOAPAction and envelope
// version taken from the matching binding.
func (g *generator) client(b *strings.Builder) {
	if len(g.d.PortTypes) == 0 {
		return
	}
	for _, ptName := range sortedKeys(g.d.PortTypes) {
		pt := g.d.PortTypes[ptName]
		svcName := exportName(pt.Name)
		endpoint, version := g.endpointFor(pt.Name)
		var ptBuf strings.Builder
		pb := &ptBuf
		fmt.Fprintf(pb, "// %sClient is a typed SOAP client for %s.\n", svcName, pt.Name)
		fmt.Fprintf(pb, "type %sClient struct {\n\tClient *soap.Client\n}\n\n", svcName)
		fmt.Fprintf(pb, "// New%sClient builds a client for the endpoint declared in the WSDL (%s).\n", svcName, endpoint)
		fmt.Fprintf(pb, "func New%sClient() *%sClient {\n\treturn &%sClient{Client: &soap.Client{Endpoint: %q, Version: %q}}\n}\n\n", svcName, svcName, svcName, endpoint, version)
		methods := 0
		for _, op := range pt.Operations {
			inType := g.messageType(op.Input)
			outType := g.messageType(op.Output)
			action := g.actionFor(pt.Name, op.Name)
			if inType == "" || outType == "" {
				fmt.Fprintf(pb, "// %s: skipped (unresolved messages)\n", exportName(op.Name))
				continue
			}
			methods++
			fmt.Fprintf(pb, "func (c *%sClient) %s(ctx context.Context, req *%s) (*%s, error) {\n", svcName, exportName(op.Name), inType, outType)
			fmt.Fprintf(pb, "\tvar out %s\n\tif err := c.Client.Call(ctx, %q, req, &out); err != nil {\n\t\treturn nil, err\n\t}\n\treturn &out, nil\n}\n\n", outType, action)
		}
		if methods > 0 {
			b.WriteString(ptBuf.String())
		}
	}
}

// endpointFor finds the service address + SOAP version for a portType.
func (g *generator) endpointFor(ptName string) (string, string) {
	for _, bd := range g.d.Bindings {
		if local(bd.Type) != ptName {
			continue
		}
		for _, svc := range g.d.Services {
			for _, p := range svc.Ports {
				if local(p.Binding) == bd.Name && p.Address != "" {
					ver := bd.SOAPVer
					if ver == "" {
						ver = "1.1"
					}
					return p.Address, ver
				}
			}
		}
		ver := bd.SOAPVer
		if ver == "" {
			ver = "1.1"
		}
		return "", ver
	}
	return "", "1.1"
}

// actionFor resolves the SOAPAction for an operation from its binding.
func (g *generator) actionFor(ptName, opName string) string {
	for _, bd := range g.d.Bindings {
		if local(bd.Type) != ptName {
			continue
		}
		for _, op := range bd.Operations {
			if op.Name == opName {
				return op.SOAPAction
			}
		}
	}
	return opName
}

// markRoots precomputes which emitted structs are message root elements,
// so they can carry a namespace-qualified XMLName on the wire.
func (g *generator) markRoots() {
	for _, m := range g.d.Messages {
		if len(m.Parts) == 0 {
			continue
		}
		p := m.Parts[0]
		if p.Element == "" {
			continue
		}
		elName := local(p.Element)
		for _, sc := range g.d.Schemas {
			el, ok := sc.Elements[elName]
			if !ok {
				continue
			}
			if sc.ElemForm != "qualified" {
				break
			}
			switch {
			case el.Inline != nil || local(el.Type) == elName:
				g.root[strings.ToLower(exportName(elName))] = rootInfo{ns: sc.TargetNS, elem: elName}
			case el.Type != "":
				g.wrap[strings.ToLower(exportName(elName))] = wrapInfo{ns: sc.TargetNS, typeName: exportName(local(el.Type))}
			}
			break
		}
	}
}

// messageType resolves a message to the Go type of its first part's
// element or type.
func (g *generator) messageType(qmsg string) string {
	m, ok := g.d.Messages[local(qmsg)]
	if !ok || len(m.Parts) == 0 {
		return ""
	}
	p := m.Parts[0]
	if p.Element != "" {
		return exportName(local(p.Element))
	}
	if p.Type != "" {
		return exportName(local(p.Type))
	}
	return ""
}

type generator struct {
	d       *wsdl.Definitions
	names   map[string]int    // lower-cased local name -> count across schemas
	emitted map[string]string // emitted Go type name -> schema targetNS
	root    map[string]rootInfo
	wrap    map[string]wrapInfo
}

// rootInfo marks a struct as a message root element: it gets an XMLName
// field carrying the target namespace, so generated requests are
// namespace-qualified on the wire (elementFormDefault="qualified").
type rootInfo struct {
	ns   string
	elem string
}

// wrapInfo marks a message element that references a named type under a
// different element name: a thin wrapper struct is emitted.
type wrapInfo struct {
	ns       string
	typeName string
}

func (g *generator) collectNameCollisions() {
	for _, sc := range g.d.Schemas {
		for name := range sc.Types {
			g.names[strings.ToLower(local(name))]++
		}
		for name := range sc.Simple {
			g.names[strings.ToLower(local(name))]++
		}
	}
}

// goType resolves an XSD-qualified type name to a Go type.
// many=true forces slice form; nillable forces pointer form.
func (g *generator) goType(sc *wsdl.Schema, xsdType string, many, nillable bool) string {
	base := xsdBuiltin(local(xsdType))
	if base == "" {
		// user type: element name or complex/simple type
		base = exportName(local(xsdType))
	}
	if many {
		return "[]" + base
	}
	if nillable && !strings.HasPrefix(base, "[]") {
		return "*" + base
	}
	return base
}

// typeKnown reports whether a qualified type name resolves to a builtin
// or a declared complex/simple type in any parsed schema.
func (g *generator) typeKnown(q string) bool {
	l := local(q)
	if xsdBuiltin(l) != "" {
		return true
	}
	for _, sc := range g.d.Schemas {
		if _, ok := sc.Types[l]; ok {
			return true
		}
		if _, ok := sc.Simple[l]; ok {
			return true
		}
		if _, ok := sc.Elements[l]; ok {
			return true
		}
	}
	return false
}

func (g *generator) complex(b *strings.Builder, sc *wsdl.Schema, ct *wsdl.ComplexType) {
	name := g.emitName(sc, exportName(ct.Name))
	if ct.Doc != "" {
		fmt.Fprintf(b, "// %s: %s\n", name, oneLine(ct.Doc))
	}
	fmt.Fprintf(b, "type %s struct {\n", name)
	if ri, ok := g.root[strings.ToLower(exportName(ct.Name))]; ok && ri.ns != "" {
		fmt.Fprintf(b, "\tXMLName xml.Name `xml:\"%s %s\"`\n", ri.ns, ri.elem)
	}
	if ct.Base != "" && g.typeKnown(ct.Base) && xsdBuiltin(local(ct.Base)) == "" {
		fmt.Fprintf(b, "\t%s\n", exportName(local(ct.Base)))
	}
	if ct.SimpleContentBase != "" {
		fmt.Fprintf(b, "\tValue %s `xml:\",chardata\"`\n", xsdBuiltinOr(local(ct.SimpleContentBase), "string"))
	}
	for _, p := range ct.Parts {
		g.particleFor(b, sc, p, false, name)
	}
	for _, a := range ct.Attributes {
		gt := g.goType(sc, a.Type, false, false)
		if gt == "" {
			gt = "string"
		}
		fmt.Fprintf(b, "\t%s %s `xml:\"%s,attr,omitempty\" json:\"%s,omitempty\"`\n", exportName(a.Name), gt, a.Name, a.Name)
	}
	b.WriteString("}\n\n")
}

// particle emits fields for one content particle, carrying the "many"
// flag down from compositor bounds. A choice with maxOccurs=unbounded
// makes every member a slice — this is the fix for the silent
// data-loss bug reproduced from hooklift/gowsdl#264.
func (g *generator) particleFor(b *strings.Builder, sc *wsdl.Schema, p *wsdl.Particle, parentMany bool, owner string) {
	many := parentMany || wsdl.Many(p.Min, p.Max)
	for _, el := range p.Elements {
		g.field(b, sc, el, many, owner)
	}
	for _, c := range p.Children {
		g.particleFor(b, sc, c, many, owner)
	}
}

func (g *generator) field(b *strings.Builder, sc *wsdl.Schema, el *wsdl.Element, parentMany bool, owner string) {
	if el.Ref != "" {
		// ref to a global element: known ones resolve, schema-language
		// refs (s:schema etc.) and unknowns keep their raw XML.
		if !g.typeKnown(el.Ref) {
			fmt.Fprintf(b, "\t%s XSDAny `xml:\"%s,omitempty\" json:\"%s,omitempty\"`\n", exportName(local(el.Ref)), local(el.Ref), local(el.Ref))
			return
		}
		el = &wsdl.Element{Name: local(el.Ref), Type: el.Ref, Min: el.Min, Max: el.Max, Nillable: el.Nillable}
	}
	name := el.Name
	if name == "" {
		name = local(el.Type)
	}
	many := parentMany || wsdl.Many(el.Min, el.Max)
	var gt string
	switch {
	case el.Inline != nil:
		// inline complex type: emit as named type alongside (once)
		tname := exportName(name)
		if _, already := g.emitted[strings.ToLower(tname)]; !already {
			g.complex(b, sc, &wsdl.ComplexType{
				Name: tname, Parts: el.Inline.Parts, Attributes: el.Inline.Attributes,
				Base: el.Inline.Base, BaseKind: el.Inline.BaseKind, SimpleContentBase: el.Inline.SimpleContentBase,
			})
		}
		gt = tname
	case el.InlineSm != nil:
		gt = xsdBuiltinOr(local(el.InlineSm.Base), "string")
	case el.Type != "":
		if !g.typeKnown(el.Type) {
			gt = "XSDAny"
		} else {
			gt = g.goType(sc, el.Type, false, false)
			if gt == "" || gt == "interface{}" {
				gt = "XSDAny"
			}
		}
	default:
		gt = "string"
	}
	if many {
		gt = "[]" + gt
	} else {
		// A struct cannot contain itself by value; self-references
		// (and nillable fields) go through pointers.
		if gt == owner || (el.Nillable && !strings.HasPrefix(gt, "[]") && !strings.HasPrefix(gt, "*") && gt != "XSDAny") {
			gt = "*" + gt
		}
	}
	omitempty := ",omitempty"
	if el.Min != "" && el.Min != "0" && !many {
		omitempty = ""
	}
	fmt.Fprintf(b, "\t%s %s `xml:\"%s%s\" json:\"%s,omitempty\"`\n", exportName(name), gt, name, omitempty, name)
}

func (g *generator) simple(b *strings.Builder, sc *wsdl.Schema, st *wsdl.SimpleType) {
	name := g.emitName(sc, exportName(st.Name))
	base := xsdBuiltinOr(local(st.Base), "string")
	if st.ListOf != "" {
		fmt.Fprintf(b, "type %s []%s\n\n", name, xsdBuiltinOr(local(st.ListOf), "string"))
		return
	}
	fmt.Fprintf(b, "type %s %s\n\n", name, base)
	for _, e := range st.Enums {
		fmt.Fprintf(b, "const %s%s %s = %q\n", name, exportName(e), name, e)
	}
	if len(st.Enums) > 0 {
		b.WriteString("\n")
	}
}

func (g *generator) globalElement(b *strings.Builder, sc *wsdl.Schema, el *wsdl.Element) {
	if el.Inline != nil || el.InlineSm != nil {
		name := exportName(el.Name)
		if _, already := g.emitted[strings.ToLower(name)]; already {
			return
		}
		switch {
		case el.Inline != nil:
			g.complex(b, sc, &wsdl.ComplexType{
				Name: name, Parts: el.Inline.Parts, Attributes: el.Inline.Attributes,
				Base: el.Inline.Base, BaseKind: el.Inline.BaseKind, SimpleContentBase: el.Inline.SimpleContentBase,
			})
		case el.InlineSm != nil:
			fmt.Fprintf(b, "type %s %s\n\n", g.emitName(sc, name), xsdBuiltinOr(local(el.InlineSm.Base), "string"))
		}
		return
	}
	if el.Type == "" {
		return
	}
	if wi, ok := g.wrap[strings.ToLower(exportName(el.Name))]; ok {
		wname := g.emitName(sc, exportName(el.Name))
		fmt.Fprintf(b, "// %s is the message root element wrapper for %s.\n", wname, wi.typeName)
		fmt.Fprintf(b, "type %s struct {\n", wname)
		if wi.ns != "" {
			fmt.Fprintf(b, "\tXMLName xml.Name `xml:\"%s %s\"`\n", wi.ns, el.Name)
		}
		fmt.Fprintf(b, "\t%s\n}\n\n", wi.typeName)
		return
	}
	// global element of a named type: no wrapper needed; xml tags on the
	// struct fields carry the names. Skip to avoid redefinition.
}

// emitName registers and returns the Go name for a schema type. When
// the same name is declared in multiple namespaces, later emissions get
// a deterministic suffix derived from the namespace URI, so no type
// silently redefines another (the gowsdl namespace-redefinition bug).
func (g *generator) emitName(sc *wsdl.Schema, name string) string {
	key := strings.ToLower(name)
	if ns, taken := g.emitted[key]; !taken || ns == sc.TargetNS {
		g.emitted[key] = sc.TargetNS
		return name
	}
	suffix := nsToken(sc.TargetNS)
	qualified := name + "_" + suffix
	g.emitted[strings.ToLower(qualified)] = sc.TargetNS
	return qualified
}

// nsToken derives a short deterministic token from a namespace URI.
func nsToken(ns string) string {
	ns = strings.TrimSuffix(ns, "/")
	if i := strings.LastIndex(ns, "/"); i >= 0 {
		ns = ns[i+1:]
	}
	var out []rune
	for _, r := range ns {
		if unicode.IsLetter(r) || unicode.IsDigit(r) {
			out = append(out, r)
		}
	}
	if len(out) == 0 {
		return "NS"
	}
	return string(out)
}

func local(q string) string {
	if i := strings.LastIndex(q, ":"); i >= 0 {
		return q[i+1:]
	}
	return q
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func sortedKeys2[A, B any](a map[string]A, b map[string]B) []string {
	seen := map[string]bool{}
	var keys []string
	for k := range a {
		keys = append(keys, k)
		seen[k] = true
	}
	for k := range b {
		if !seen[k] {
			keys = append(keys, k)
		}
	}
	sort.Strings(keys)
	return keys
}

func exportName(s string) string {
	if s == "" {
		return "Field"
	}
	var out []rune
	upperNext := true
	for _, r := range s {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			upperNext = true
			continue
		}
		if upperNext {
			r = unicode.ToUpper(r)
			upperNext = false
		}
		out = append(out, r)
	}
	if len(out) == 0 {
		return "Field"
	}
	return string(out)
}

func sanitizeIdent(s string) string {
	var out []rune
	for i, r := range s {
		if !unicode.IsLetter(r) && !(unicode.IsDigit(r) && i > 0) && r != '_' {
			continue
		}
		out = append(out, unicode.ToLower(r))
	}
	if len(out) == 0 {
		return "myservice"
	}
	return string(out)
}

func oneLine(s string) string {
	return strings.Join(strings.Fields(s), " ")
}

func xsdBuiltinOr(name, fallback string) string {
	if t := xsdBuiltin(name); t != "" {
		return t
	}
	return fallback
}

// xsdBuiltin maps XML Schema built-in types to Go types. Decimal maps
// to float64 (documented: exact decimal arithmetic is out of scope).
// dateTime/date map to time.Time via the XSDDateTime/XSDDate helpers
// emitted into every generated file.
func xsdBuiltin(name string) string {
	switch name {
	case "string", "normalizedString", "token", "language", "Name", "NCName", "NMTOKEN", "ID", "IDREF", "anyURI", "QName", "duration", "gYear", "gYearMonth", "gMonth", "gDay", "gMonthDay", "NOTATION":
		return "string"
	case "boolean":
		return "bool"
	case "byte", "short", "int", "integer", "nonPositiveInteger", "negativeInteger", "nonNegativeInteger", "positiveInteger", "unsignedByte", "unsignedShort":
		return "int"
	case "long", "unsignedInt":
		return "int64"
	case "unsignedLong":
		return "uint64"
	case "float", "double", "decimal":
		return "float64"
	case "dateTime", "date", "time":
		return "XSDDateTime"
	case "base64Binary", "hexBinary":
		return "[]byte"
	case "anyType", "anySimpleType":
		return "interface{}"
	}
	return ""
}

// helperTypes is emitted into every generated file so generated code is
// self-contained (no runtime dependency on lather).
const helperTypes = `// XSDDateTime wraps time.Time with XML Schema dateTime (RFC 3339)
// marshalling, accepting the fractional-second and timezone variants
// real SOAP endpoints produce.
type XSDDateTime struct{ time.Time }

const xsdDateTimeFormat = "2006-01-02T15:04:05.999999999Z07:00"

func (t XSDDateTime) MarshalXML(e *xml.Encoder, start xml.StartElement) error {
	return e.EncodeElement(t.Format(xsdDateTimeFormat), start)
}

func (t *XSDDateTime) UnmarshalXML(d *xml.Decoder, start xml.StartElement) error {
	var s string
	if err := d.DecodeElement(&s, &start); err != nil {
		return err
	}
	v, err := time.Parse(xsdDateTimeFormat, strings.TrimSpace(s))
	if err != nil {
		v, err = time.Parse("2006-01-02T15:04:05", strings.TrimSpace(s))
	}
	if err != nil {
		return err
	}
	t.Time = v
	return nil
}

// XSDAny keeps the raw XML of content whose schema type is unknown or
// unstructured (xsd:any, .NET DataSet payloads, unresolved refs). No
// bytes are dropped: the raw XML is preserved verbatim.
type XSDAny struct {
	Raw string ` + "`xml:\",innerxml\"`" + `
}

`
